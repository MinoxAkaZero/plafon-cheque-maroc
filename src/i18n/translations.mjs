/**
 * Translates a key strictly for the requested language (never silently mixes languages).
 */
export function translateKey(lang, key, params = {}) {
  const safeLang = SUPPORTED_LANGUAGES.includes(lang) ? lang : 'fr';
  const dict = PCM_I18N[safeLang];
  if (!dict || typeof dict[key] !== 'string' || dict[key].length === 0) {
    return `[MISSING:${safeLang}.${key}]`;
  }
  return dict[key].replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

/**
 * Development-time translation parity detector across EN, AR, and FR.
 */
export function auditTranslationParity(dictionary = PCM_I18N) {
  const allKeys = new Set();
  for (const lang of SUPPORTED_LANGUAGES) {
    Object.keys(dictionary[lang] || {}).forEach((k) => allKeys.add(k));
  }
  const missing = [];
  for (const lang of SUPPORTED_LANGUAGES) {
    const pack = dictionary[lang] || {};
    for (const k of allKeys) {
      if (typeof pack[k] !== 'string' || pack[k].trim().length === 0) {
        missing.push(`${lang}.${k}`);
      }
    }
  }
  return {
    ok: missing.length === 0,
    totalKeysPerLanguage: allKeys.size,
    languagesChecked: [...SUPPORTED_LANGUAGES],
    missing
  };
}
